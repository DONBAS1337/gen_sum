def find_root(game_dir, seven_dl_root=None, environ=None):
    environ = os.environ if environ is None else environ
    steamapps = os.path.abspath(os.path.join(game_dir, '..', '..', '..'))
    candidates = [environ.get('DON_GEN_BKRR_ROOT'),
                  os.path.join(steamapps, 'workshop', 'content', '331470', '451835368')]
    if seven_dl_root:
        candidates.append(os.path.join(os.path.dirname(seven_dl_root), '451835368'))
    for root in candidates:
        if not root:
            continue
        if os.path.basename(os.path.normpath(root)).lower() == 'bkrr':
            root = os.path.dirname(os.path.normpath(root))
        if os.path.isfile(os.path.join(root, 'bkrr', 'bkrr.rpy')):
            return os.path.abspath(root)
    return None


